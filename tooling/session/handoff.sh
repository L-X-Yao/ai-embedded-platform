#!/bin/bash
# handoff.sh — generate docs/session-state.md for cross-session continuity.
#
# Captures: last audit round, pending items, quality snapshot, suggested next action.
# Run at session end: make handoff

set -euo pipefail

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
OUT="$REPO/docs/session-state.md"

# --- Last audit round ---
last_audit=$(grep -c "超级审计" "$REPO/docs/audit-dimensions.md" 2>/dev/null || echo "0")
last_audit_line=$(grep "超级审计" "$REPO/docs/audit-dimensions.md" 2>/dev/null | tail -1 || echo "none")
last_audit_date=$(echo "$last_audit_line" | awk -F'|' '{print $2}' | xargs 2>/dev/null) || true
last_audit_date=${last_audit_date:-unknown}

# --- Wheels changed since last audit ---
last_audit_commit=$(git -C "$REPO" log --oneline --grep="audit history" -1 --format=%H 2>/dev/null || echo "")
if [ -n "$last_audit_commit" ]; then
    wheels_changed=$(git -C "$REPO" diff --name-only "$last_audit_commit" HEAD -- wheels/ 2>/dev/null | grep -c "\.c$" || true)
else
    wheels_changed="unknown"
fi

# --- Quality snapshot ---
quality=$(python3 "$REPO/tooling/metrics/platform_metrics_impl.py" "$REPO" "$REPO/.metrics" --quality 2>/dev/null | grep -v "===" || echo "  (unavailable)")

# --- Pending items from known-issues.md ---
pending_tests=$(grep "untested" "$REPO/docs/known-issues.md" 2>/dev/null | head -5 || echo "  (none)")

# --- Git status ---
uncommitted=$(git -C "$REPO" status --porcelain 2>/dev/null | wc -l | xargs)
branch=$(git -C "$REPO" branch --show-current 2>/dev/null || echo "unknown")

cat > "$OUT" << EOF
# Session State

Auto-generated by \`make handoff\`. Read by \`make bootstrap\` on next session start.

## Last Session
- **Date**: $(date +%Y-%m-%d)
- **Branch**: $branch
- **Audit rounds completed**: $last_audit (last: $last_audit_date)
- **Wheels .c files changed since last audit**: $wheels_changed
- **Uncommitted changes**: $uncommitted

## Quality Snapshot
$quality

## Remaining Test Gaps
$pending_tests

## Suggested Next Actions
EOF

# --- Smart suggestions ---
wheels_changed_num=$(echo "$wheels_changed" | tr -dc '0-9')
wheels_changed_num=${wheels_changed_num:-0}
if [ "$wheels_changed_num" -gt 10 ] 2>/dev/null; then
    echo "- **Run super audit**: $wheels_changed wheel files changed since last audit" >> "$OUT"
fi
if [ "$uncommitted" -gt 0 ]; then
    echo "- **Commit pending changes**: $uncommitted files modified" >> "$OUT"
fi
echo "- Review \`docs/known-issues.md\` remaining test gaps section" >> "$OUT"
echo "- Consider external-input-driven audit angles (new project, CVE, user bug report)" >> "$OUT"

echo "Generated: $OUT"

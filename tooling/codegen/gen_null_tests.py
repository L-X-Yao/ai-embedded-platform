#!/usr/bin/env python3
"""gen_null_tests.py -- generate NULL-parameter rejection tests for wheels.

For each wheel with a public .h file, parses function declarations that accept
pointer parameters and generates a test_null_<name>.c that passes NULL for each
pointer param (one test per pointer param), asserting the function returns an
error code or at least does not crash.

Usage:
    python tooling/codegen/gen_null_tests.py [--dry-run]
    python tooling/codegen/gen_null_tests.py --wheel wheels/drivers/mcp4725
    python tooling/codegen/gen_null_tests.py --wheel wheels/drivers/mcp4725/mcp4725.h
"""

import argparse
import re
import sys
from pathlib import Path

from _wheel_parser import (
    REPO_ROOT, WHEELS_DIR,
    WheelInfo,
    read_header,
    parse_functions,
    classify_return_type,
    scalar_default,
    discover_wheels,
)

# ---------------------------------------------------------------------------
# Default value generation for non-NULL params
# ---------------------------------------------------------------------------

def make_default_value(param, wheel_name: str, idx: int) -> tuple:
    """Generate a variable declaration + value for a non-NULL param.

    Returns (decl_lines: list[str], var_name: str).
    """
    ptype = param.type_text.strip()
    pname = param.name or f"arg{idx}"

    # Function pointer typedef: use NULL
    if param.is_func_ptr:
        return ([], "NULL")

    # Strip const for the local variable
    base = ptype.replace('const ', '').strip()

    # Pointer to a struct: declare zero-initialized struct
    if '*' in base:
        star_count = base.count('*')
        var = f"__{pname}_{idx}"
        if star_count >= 2:
            # Double (or higher) pointer: declare a single-pointer initialized
            # to NULL and pass its address.  A flat array would give the wrong
            # type (e.g. char[] instead of char **).
            # Preserve 'const' on the inner type so that e.g. const char **
            # gets const char *inner = NULL  (char * would not be compatible).
            inner_base = base.replace('*', '').strip() or 'uint8_t'
            has_const = 'const' in ptype
            inner_type = ('const ' + inner_base) if has_const else inner_base
            decl = f"    {inner_type} *{var} = NULL;"
            return ([decl], f"&{var}")
        else:
            pointed_type = base.replace('*', '').strip()
            if not pointed_type:
                pointed_type = 'uint8_t'
            decl = f"    {pointed_type} {var};"
            init = f"    memset(&{var}, 0, sizeof({var}));"
            return ([decl, init], f"&{var}")

    # Non-pointer: use type-appropriate default
    return ([], scalar_default(param.type_text))


def make_dummy_for_type(type_text: str, var_name: str) -> list:
    """Create a dummy variable declaration for a given type."""
    base = type_text.replace('const ', '').replace('*', '').strip()
    if not base:
        return [f"    uint8_t {var_name} = 0;"]
    return [
        f"    {base} {var_name};",
        f"    memset(&{var_name}, 0, sizeof({var_name}));",
    ]


# ---------------------------------------------------------------------------
# Test file generation
# ---------------------------------------------------------------------------

def generate_test_file(wheel: WheelInfo) -> str:
    """Generate the complete test_null_<name>.c file content."""
    name = wheel.name
    lines = []
    test_names = []

    lines.append(f"// Auto-generated NULL parameter tests for {name}")
    lines.append(f"// Generated by gen_null_tests.py -- do not edit manually")
    lines.append("")
    lines.append('#include "test_harness.h"')
    lines.append(f'#include "../{name}.h"')
    lines.append('#include <string.h>')
    lines.append('#include <stddef.h>')
    lines.append("")

    for func in wheel.funcs:
        ptr_params = [(i, p) for i, p in enumerate(func.params)
                      if p.is_pointer and not p.is_func_ptr]
        if not ptr_params:
            continue

        ret_class = classify_return_type(func.return_type, name)

        for null_idx, null_param in ptr_params:
            pname = null_param.name or f"arg{null_idx}"
            test_name = f"test_{func.name}_null_{pname}"
            test_names.append(test_name)

            lines.append(f"TEST({test_name}) {{")

            call_args = []
            decl_lines = []

            for i, param in enumerate(func.params):
                if i == null_idx:
                    call_args.append("NULL")
                    continue

                if param.is_pointer and not param.is_func_ptr:
                    raw_base = param.type_text.replace('const ', '').strip()
                    star_count = raw_base.count('*')
                    ptype_base = raw_base.replace('*', '').strip()
                    local_name = param.name or f"arg{i}"
                    var = f"_{local_name}"

                    if not ptype_base:
                        ptype_base = "uint8_t"

                    # void* params: pass NULL (can't stack-allocate void)
                    if ptype_base == 'void':
                        call_args.append("NULL")
                    # Double (or higher) pointer: declare a single-pointer
                    # initialized to NULL and take its address.  Allocating a
                    # flat array would yield the wrong type (e.g. char[]
                    # instead of char **).
                    elif star_count >= 2:
                        # Preserve const qualifier on the inner pointer so
                        # types stay compatible (e.g. const char **).
                        has_const = 'const' in param.type_text
                        inner_qualified = ('const ' + ptype_base) if has_const else ptype_base
                        decl_lines.append(f"    {inner_qualified} *{var} = NULL;")
                        call_args.append(f"&{var}")
                    # Buffer params: allocate a small array
                    elif ptype_base in ('uint8_t', 'char', 'int8_t'):
                        decl_lines.append(f"    {ptype_base} {var}[64];")
                        decl_lines.append(f"    memset({var}, 0, sizeof({var}));")
                        call_args.append(var)
                    else:
                        decl_lines.append(f"    {ptype_base} {var};")
                        decl_lines.append(f"    memset(&{var}, 0, sizeof({var}));")
                        call_args.append(f"&{var}")
                elif param.is_func_ptr:
                    call_args.append("NULL")
                else:
                    call_args.append(scalar_default(param.type_text))

            for dl in decl_lines:
                lines.append(dl)

            args_str = ", ".join(call_args)
            lines.append(f"    (void){func.name}({args_str});")
            lines.append(f"    /* must not crash */")
            lines.append("}")
            lines.append("")

    if not test_names:
        return ""

    lines.append(f'TEST_MAIN("null_param_{name}") {{')
    for tn in test_names:
        lines.append(f"    RUN({tn});")
    lines.append("}")
    lines.append("TEST_MAIN_END()")
    lines.append("")

    return "\n".join(lines)


# ---------------------------------------------------------------------------
# CMakeLists.txt auto-registration
# ---------------------------------------------------------------------------

def update_cmakelists(wheel: WheelInfo, dry_run: bool) -> bool:
    """Add test_null_<name> target to CMakeLists.txt if missing.

    Returns True if the file was updated (or would be in dry-run).
    """
    cmake_path = wheel.path / "test" / "CMakeLists.txt"
    if not cmake_path.is_file():
        return False

    content = cmake_path.read_text(encoding="utf-8")
    target = f"test_null_{wheel.name}"

    if target in content:
        return False

    # Extract source files from existing add_executable
    src_re = re.compile(r'add_executable\(\s*test_' + re.escape(wheel.name)
                        + r'\s*\n(.*?)\)', re.DOTALL)
    src_match = src_re.search(content)
    sources = [f"../{wheel.name}.c"]
    if src_match:
        src_block = src_match.group(1)
        for line in src_block.strip().split('\n'):
            s = line.strip()
            if s.startswith('../') and s.endswith('.c'):
                if s not in sources:
                    sources.append(s)

    has_contract = 'CONTRACT_ENABLED' in content
    has_enable_testing = 'enable_testing()' in content

    src_list = "\n".join(f"    {s}" for s in [f"{target}.c"] + sources)
    block_lines = [
        "",
        f"add_executable({target}",
        src_list,
        ")",
        f"target_include_directories({target} PRIVATE",
        "    ${CMAKE_CURRENT_SOURCE_DIR}/..",
        "    ${CMAKE_CURRENT_SOURCE_DIR}/../../../../tooling/harness",
        ")",
    ]
    if has_contract:
        block_lines.append(
            f"target_compile_definitions({target} PRIVATE CONTRACT_ENABLED)")
    block_lines.append(
        f"target_compile_options({target} PRIVATE"
        " -Wall -Wextra -Wpedantic -Werror -Wconversion)")

    test_line = f"add_test(NAME {wheel.name}_null_tests COMMAND {target})"

    lines = content.rstrip('\n').split('\n')

    if has_enable_testing:
        et_idx = next(i for i, l in enumerate(lines)
                      if 'enable_testing()' in l)
        for j, bl in enumerate(block_lines):
            lines.insert(et_idx + j, bl)
        lines.append(test_line)
    else:
        lines.extend(block_lines)
        lines.append("")
        lines.append("enable_testing()")
        lines.append(test_line)

    new_content = "\n".join(lines) + "\n"

    if dry_run:
        print(f"  [DRY-RUN] Would update {cmake_path.relative_to(REPO_ROOT)}")
    else:
        cmake_path.write_bytes(new_content.encode("utf-8"))
        print(f"  Updated  {cmake_path.relative_to(REPO_ROOT)}"
              f" (added {target} target)")

    return True


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def resolve_single_wheel(path_arg: str) -> list:
    """Resolve a --wheel argument to a single-element WheelInfo list."""
    p = Path(path_arg).resolve()
    if p.suffix == '.h':
        p = p.parent
    if not p.is_dir():
        print(f"Error: {path_arg} is not a valid wheel directory", file=sys.stderr)
        sys.exit(1)
    header = p / f"{p.name}.h"
    if not header.is_file():
        print(f"Error: no {p.name}.h found in {p}", file=sys.stderr)
        sys.exit(1)
    rel = p.relative_to(WHEELS_DIR)
    layer = rel.parts[0]
    return [WheelInfo(name=p.name, layer=layer, path=p, header_path=header)]


def main():
    parser = argparse.ArgumentParser(
        description="Generate NULL-parameter rejection tests for wheels."
    )
    parser.add_argument("--dry-run", action="store_true",
                        help="print actions without writing files")
    parser.add_argument("--wheel", default=None,
                        help="single wheel path (e.g. wheels/drivers/mcp4725 or .h file)")
    parser.add_argument("header", nargs="?", default=None,
                        help="positional shortcut: path to a single .h file")
    args = parser.parse_args()
    dry_run = args.dry_run
    single = args.wheel or args.header

    if single:
        wheels = resolve_single_wheel(single)
        print(f"Single-wheel mode: {wheels[0].layer}/{wheels[0].name}")
    else:
        wheels = discover_wheels()
        print(f"Discovered {len(wheels)} wheels with public headers")

    generated = 0
    skipped_no_ptrs = 0
    skipped_no_funcs = 0
    total_tests = 0
    errors = []

    for wheel in wheels:
        try:
            header_text = read_header(wheel.header_path)
            funcs = parse_functions(header_text, wheel.name)
            wheel.funcs = funcs

            if not funcs:
                skipped_no_funcs += 1
                continue

            has_ptr = any(
                p.is_pointer and not p.is_func_ptr
                for f in funcs for p in f.params
            )
            if not has_ptr:
                # Generate placeholder for value-only APIs so audit doesn't warn
                content = (
                    f'#include "test_harness.h"\n'
                    f'#include "{wheel.name}.h"\n\n'
                    f'/* All functions take value parameters only — no NULL to test. */\n\n'
                    f'TEST(test_value_only_api)\n'
                    f'{{\n'
                    f'    /* Placeholder: {wheel.name} has no pointer parameters. */\n'
                    f'    ASSERT_EQ(0, 0);\n'
                    f'}}\n\n'
                    f'TEST_MAIN("{wheel.name}_null")\n'
                    f'    RUN(test_value_only_api);\n'
                    f'TEST_MAIN_END()\n'
                )
                test_dir = wheel.path / "test"
                out_path = test_dir / f"test_null_{wheel.name}.c"
                if not dry_run:
                    test_dir.mkdir(parents=True, exist_ok=True)
                    out_path.write_bytes(content.encode("utf-8"))
                    print(f"  Placeholder {wheel.layer}/{wheel.name}: "
                          f"value-only API -> {out_path.relative_to(REPO_ROOT)}")
                else:
                    print(f"  [DRY-RUN] Placeholder {wheel.layer}/{wheel.name}: value-only API")
                update_cmakelists(wheel, dry_run)
                generated += 1
                total_tests += 1
                continue

            content = generate_test_file(wheel)
            if not content:
                skipped_no_ptrs += 1
                continue

            n_tests = content.count("TEST(test_")
            total_tests += n_tests

            test_dir = wheel.path / "test"
            out_path = test_dir / f"test_null_{wheel.name}.c"

            if dry_run:
                print(f"  [DRY-RUN] {wheel.layer}/{wheel.name}: "
                      f"{len(wheel.funcs)} funcs, {n_tests} null tests")
            else:
                test_dir.mkdir(parents=True, exist_ok=True)
                out_path.write_bytes(content.encode("utf-8"))
                print(f"  Generated {wheel.layer}/{wheel.name}: "
                      f"{len(wheel.funcs)} funcs, {n_tests} null tests -> "
                      f"{out_path.relative_to(REPO_ROOT)}")

            update_cmakelists(wheel, dry_run)
            generated += 1

        except Exception as e:
            errors.append((wheel.name, str(e)))
            print(f"  ERROR {wheel.layer}/{wheel.name}: {e}")

    print(f"\n{'=' * 60}")
    print(f"Summary:")
    print(f"  Wheels discovered:      {len(wheels)}")
    print(f"  Files generated:        {generated}")
    print(f"  Total NULL tests:       {total_tests}")
    print(f"  Skipped (no functions):  {skipped_no_funcs}")
    print(f"  Skipped (no ptr params): {skipped_no_ptrs}")
    print(f"  Errors:                  {len(errors)}")
    if errors:
        for name, err in errors:
            print(f"    {name}: {err}")
    print(f"{'=' * 60}")


if __name__ == "__main__":
    main()
